"""Writer/reader for GENERATED POC/js/data/errp-*.js files in the ADR 0004 D18 format.

Kept inside research/errp/ (ERRP-owned); mirrors research/export/jsdata.py's documented format so the
EXPORT builder's reader can parse it. Float32 little-endian base64, wrapped at 1000 chars per line.
"""
from __future__ import annotations

import base64
import hashlib
import json
import re

import numpy as np

WRAP = 1000


def f32_b64(a: np.ndarray) -> str:
    return base64.b64encode(np.ascontiguousarray(a, dtype="<f4").tobytes()).decode("ascii")


def b64_f64(s: str) -> np.ndarray:
    return np.frombuffer(base64.b64decode(s), dtype="<f4").astype(np.float64)


def _wrap_join(s: str, indent: str = "") -> str:
    parts = [s[i:i + WRAP] for i in range(0, len(s), WRAP)] or [""]
    return "[\n" + ",\n".join(f'{indent}"{p}"' for p in parts) + "\n" + indent + '].join("")'


def _num(o):
    """JSON with Python repr floats (17 significant digits via repr)."""
    return json.dumps(o, separators=(", ", ": "), allow_nan=False)


def write_js(path: str, name: str, obj: dict, run: dict, source: str, licence: str,
             script: str = "research/errp/export.py", b64_fields: dict | None = None) -> dict:
    """obj: JSON-able dict assigned to SA.data.<name>. b64_fields: {record_index: b64 string} for
    obj['epochs'][i].dataB64 (written wrapped). Returns {bytes, sha256}."""
    body = _num(obj)
    if b64_fields:
        # replace placeholders "__B64_i__" with wrapped joins
        for i, s in b64_fields.items():
            body = body.replace(f'"__B64_{i}__"', _wrap_join(s, "  "))
    payload = f"SA.data.{name} = {body};\n"
    sha = hashlib.sha256(payload.encode("utf-8")).hexdigest()
    head = (f"/* GENERATED by {script} — DO NOT EDIT\n"
            f" * run: {run['id']}  plan: {run['plan']}  preliminary: {str(run['preliminary']).lower()}  "
            f"stub: {str(run['stub']).lower()}\n"
            f" * source: {source}  licence: {licence} — embedding pending supervisor confirmation\n"
            f" * payload-sha256: {sha}  bytes: {len(payload.encode('utf-8'))}\n"
            f" */\n")
    text = (head + "(function (root) { var SA = root.SA = root.SA || {}; SA.data = SA.data || {};\n"
            + payload + "})(typeof window !== 'undefined' ? window : globalThis);\n")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return dict(bytes=len(text.encode("utf-8")), sha256=sha)


def read_js(path: str) -> dict:
    """Parse a file written by write_js back to a dict (b64 joins collapsed to strings)."""
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    m = re.search(r"SA\.data\.(\w+) = (.*);\n\}\)\(typeof window", text, re.S)
    body = m.group(2)
    body = re.sub(r'\[\n((?:\s*"[A-Za-z0-9+/=]*",?\n)+)\s*\]\.join\(""\)',
                  lambda mm: '"' + "".join(re.findall(r'"([A-Za-z0-9+/=]*)"', mm.group(1))) + '"', body)
    return json.loads(body)
