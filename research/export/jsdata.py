"""Writer for GENERATED browser data files (docs/architecture.md §7.1).

    write_js(path, name, obj, script=..., run=..., source=..., licence=...)

- Arrays go in as ``B64(np.ndarray)`` markers; they are written as float32 little-endian
  base64 split into ``["<=1000 chars", ...].join("")`` literals.
- Everything else is JSON (Python floats serialise with ``repr``: shortest round-trip,
  i.e. exact float64 values).
- Header carries run / plan / stub / source / licence / payload sha256 / byte count.
"""
import base64
import hashlib
import json
import os

import numpy as np

CHUNK = 1000


class B64(object):
    """Marker: serialise ``arr`` as float32-LE base64 (one rounding, D23)."""

    def __init__(self, arr):
        self.arr = np.ascontiguousarray(np.asarray(arr, dtype="<f4")).ravel()

    def encode(self):
        return base64.b64encode(self.arr.tobytes()).decode("ascii")


def f32_b64(arr):
    return B64(arr).encode()


def f32_bytes(arr):
    return np.ascontiguousarray(np.asarray(arr, dtype="<f4")).tobytes()


def decode_f32(s):
    """Python mirror of SA.core.b64.decodeF32 (float64 out)."""
    return np.frombuffer(base64.b64decode(s), dtype="<f4").astype(np.float64)


def _js_chunks(s):
    parts = [s[i:i + CHUNK] for i in range(0, len(s), CHUNK)] or [""]
    return "[" + ",\n".join(json.dumps(p) for p in parts) + "].join(\"\")"


def _clean(o):
    if isinstance(o, dict):
        return {str(k): _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    if isinstance(o, np.ndarray):
        return _clean(o.tolist())
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if isinstance(o, float) and not np.isfinite(o):
        raise ValueError("non-finite number in data payload")
    return o


def render(name, obj):
    """Return the JS assignment body ``SA.data.<name> = {...};`` with b64 literals."""
    blobs = []

    def sub(o):
        if isinstance(o, B64):
            blobs.append(o.encode())
            return "@@B64_%d@@" % (len(blobs) - 1)
        if isinstance(o, dict):
            return {k: sub(v) for k, v in o.items()}
        if isinstance(o, (list, tuple)):
            return [sub(v) for v in o]
        return o

    body = json.dumps(_clean(sub(obj)), ensure_ascii=False, allow_nan=False)
    for i, s in enumerate(blobs):
        body = body.replace('"@@B64_%d@@"' % i, _js_chunks(s), 1)
    return "SA.data.%s = %s;" % (name, body)


def write_js(path, name, obj, script, run, source, licence):
    body = render(name, obj)
    payload = body.encode("utf-8")
    sha = hashlib.sha256(payload).hexdigest()
    header = (
        "/* GENERATED by research/export/%s — DO NOT EDIT\n"
        " * run: %s  plan: %s  preliminary: %s  stub: %s\n"
        " * source: %s  licence: %s — embedding pending supervisor confirmation\n"
        " * payload-sha256: %s  bytes: %d\n"
        " */\n" % (script, run.get("id"), run.get("plan", "B"),
                   str(run.get("preliminary", True)).lower(), str(run.get("stub")).lower(),
                   source, licence, sha, len(payload)))
    text = (header
            + "(function (root) { var SA = root.SA = root.SA || {}; SA.data = SA.data || {};\n"
            + body + "\n"
            + "})(typeof window !== 'undefined' ? window : globalThis);\n")
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, path)
    return {"path": path, "bytes": len(text.encode("utf-8")), "sha256": sha}


def read_js(path):
    """Parse a GENERATED data file back to (header_text, obj); b64 joins become strings."""
    import re
    with open(path, encoding="utf-8") as f:
        text = f.read()
    header = text[:text.index("*/") + 2]
    m = re.search(r"SA\.data\.(\w+) = (.*);\n\}\)\(typeof window", text, re.S)
    if not m:
        raise ValueError("not a GENERATED SA.data file: %s" % path)
    body = re.sub(r'\[((?:"[A-Za-z0-9+/=]*",?\n?)+)\]\.join\(""\)',
                  lambda g: '"' + "".join(re.findall(r'"([A-Za-z0-9+/=]*)"', g.group(1))) + '"', m.group(2))
    return header, m.group(1), json.loads(body)
