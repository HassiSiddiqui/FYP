# ----------------------------------------------------------------- weights

def test_weights_manifest_and_tensors(W):
    import torch
    from export import reference as ref
    _, _, obj = W
    man = obj["manifest"]
    assert man["format"] == "sfegat-weights/1"
    assert man["classes"] == CLASSES and man["tokens"] == ["PREV", "NEXT", "SELECT", "BACK"]
    assert man["channels"] == CHANNELS and man["fs"] == 250 and man["nSamples"] == 1000
    assert man["model"]["nParams"] == 149_796 and man["totalElements"] == 151_012
    assert man["graph"]["tau"] == 0.3 and man["mask"]["eta"] == 0.5
    assert len(man["norm"]["trainBandPowerMedian"]) == 22 * 8
    flat = jsdata.decode_f32(obj["b64"])
    assert flat.size == 151_012
    if man["run"]["stub"]:
        model = ref.make_model(ref.P0, None, seed=0)
        assert man["calibration"]["temperature"] is None
    else:
        model = ref.make_model(ref.P0, os.path.join(ROOT, man["source"]))
        T = man["calibration"]["temperature"]
        assert T is not None and 0.05 <= T <= 20
    sd = {k: v for k, v in model.state_dict().items() if not k.endswith("num_batches_tracked")}
    assert [t["name"] for t in man["tensors"]] == list(sd)
    for t in man["tensors"]:
        v = sd[t["name"]].numpy().astype(np.float32)
        assert t["shape"] == list(v.shape) and t["length"] == v.size
        np.testing.assert_array_equal(flat[t["offset"]:t["offset"] + t["length"]].astype(np.float32), v.ravel())
    assert man["tensors"][0]["name"] == "stem.att" and man["tensors"][0]["shape"] == [1, 4, 32]
    assert torch is not None


def test_weights_sos_are_scipy(W):
    from scipy import signal
    man = W[2]["manifest"]
    for (lo, hi), sos, zi in zip(man["features"]["bands"], man["features"]["sos"], man["features"]["zi"]):
        ref = signal.butter(4, [lo, hi], btype="bandpass", fs=250, output="sos")
        np.testing.assert_array_equal(np.asarray(sos), ref)  # repr round-trip: exact
        np.testing.assert_array_equal(np.asarray(zi), signal.sosfilt_zi(ref))
    assert len(man["features"]["sos"]) == 8 and all(len(s) == 4 for s in man["features"]["sos"])


# ----------------------------------------------------------------- replay

def test_replay_records(R, W, A01):
    _, XE, yE = A01
    _, _, obj = R
    man = obj["manifest"]
    recs = obj["records"]
    stub = man["run"]["stub"]
    per = 1 if stub else 5
    assert len(recs) == 4 * per
    assert [sum(r["trueCls"] == c for r in recs) for c in CLASSES] == [per] * 4
    assert len({r["id"] for r in recs}) == len(recs)
    assert man["subject"] == "A01" and man["session"] == "E" and man["channels"] == CHANNELS
    assert "Brunner et al. 2008" in man["licence"] and "pending supervisor confirmation" in man["licence"]
    assert man["exemplarId"] in {r["id"] for r in recs}
    assert man["run"]["id"] == W[2]["manifest"]["run"]["id"], "replay expected values from a different model"
    if not stub:
        assert man["deployment"]["temperature"] == W[2]["manifest"]["calibration"]["temperature"]
    for r in recs:
        x = jsdata.decode_f32(r["b64"])
        assert x.size == 22 * 1000
        i = r["index"]
        assert r["id"] == "A01E-t%03d" % i and CLASSES[int(yE[i])] == r["trueCls"]
        np.testing.assert_array_equal(x.reshape(22, 1000), XE[i].astype(np.float32).astype(np.float64))
        assert hashlib.sha256(x.astype("<f4").tobytes()).hexdigest() == r["sha256"]
        e = r["expected"]
        assert len(e["logits"]) == 4 and abs(sum(e["probs"]) - 1) < 1e-12 and e["pred"] in CLASSES
        assert e["edgeCounts"] == sorted(e["edgeCounts"], reverse=True)


def test_replay_selection_rule(R, A01):
    """First `per` per class in trial order among margin-passing trials; label-blind otherwise."""
    _, _, yE = A01
    man, recs = R[2]["manifest"], R[2]["records"]
    per = len(recs) // 4
    bad = {e["index"] for e in man["selection"]["excluded"]}
    want = []
    for c in range(4):
        want += [i for i in range(len(yE)) if yE[i] == c and i not in bad][:per]
    assert sorted(r["index"] for r in recs) == sorted(want)
    assert man["selection"]["nFailedMargin"] == len(bad)


def test_replay_trials_unseen(R, A01):
    """ADR-0001 D22: every exported trial hashes to an A01E trial and to no A01T trial."""
    XT, XE, _ = A01
    hT = {_sha(x) for x in XT}
    hE = {_sha(x) for x in XE}
    for r in R[2]["records"]:
        h = _sha(jsdata.decode_f32(r["b64"]).reshape(22, 1000))
        assert h == r["sha256"]
        assert h in hE, r["id"]
        assert h not in hT, r["id"]


def test_replay_expected_reproduces(R, W):
    """Re-run the float64 reference on two exported records; must equal `expected` exactly-ish."""
    from export import reference as ref
    wm = W[2]["manifest"]
    model = ref.make_model(ref.P0, None if wm["run"]["stub"] else os.path.join(ROOT, wm["source"]), seed=0)
    for r in R[2]["records"][:2]:
        x = jsdata.decode_f32(r["b64"]).reshape(22, 1000)
        out = ref.reference(model, x, ref.P0, wm["calibration"]["temperature"])
        assert np.max(np.abs(out["logits"] - np.asarray(r["expected"]["logits"]))) <= 1e-9
        assert out["edgeCounts"] == r["expected"]["edgeCounts"] and out["margin"]["ok"]


# ----------------------------------------------------------------- montage

def test_montage():
    _, name, obj = jsdata.read_js(M_JS)
    ch = obj["channels"]
    assert [c["name"] for c in ch] == CHANNELS and [c["paperIdx"] for c in ch] == list(range(1, 23))
    pos = {c["name"]: (c["x"], c["y"]) for c in ch}
    assert abs(pos["Cz"][0]) < 0.1 and abs(pos["Cz"][1]) < 0.1
    assert pos["Fz"][1] > 0.3 and pos["POz"][1] < -0.3          # +y = nose
    assert pos["C3"][0] < -0.2 and pos["C4"][0] > 0.2           # +x = right
    assert all(np.hypot(*p) <= 1.0 for p in pos.values())
    assert obj["manifest"]["source"].startswith("MNE 1.13.2")
