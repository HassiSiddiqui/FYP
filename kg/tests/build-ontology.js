#!/usr/bin/env node
/*
 * Generates POC/js/kg/ontology.js from kg/silentassist.ttl (byte-identical
 * string) and kg/tests/cq-defs.js (competency questions). Run after editing
 * either source:   node kg/tests/build-ontology.js
 */
'use strict';
var fs = require('fs'), path = require('path');
var ROOT = path.resolve(__dirname, '..', '..');
var ttl = fs.readFileSync(path.join(ROOT, 'kg', 'silentassist.ttl'), 'utf8');
if (/\r/.test(ttl)) throw new Error('kg/silentassist.ttl must be LF only');
if (/[^\x00-\x7f]/.test(ttl)) throw new Error('kg/silentassist.ttl must be ASCII only');
var cqs = require('./cq-defs.js');

var out = '/* GENERATED by kg/tests/build-ontology.js from kg/silentassist.ttl and kg/tests/cq-defs.js - do not edit. */\n' +
  '/* SA.kg.ontologyTTL is byte-identical to kg/silentassist.ttl (kg/tests/load.test.js). */\n' +
  '(function (root) {\n' +
  '  \'use strict\';\n' +
  '  var SA = root.SA = root.SA || {};\n' +
  '  SA.kg = SA.kg || {};\n' +
  '  SA.kg.ontologyTTL = ' + JSON.stringify(ttl) + ';\n' +
  '  SA.kg.competencyQuestions = ' + JSON.stringify(cqs, null, 1) + ';\n' +
  '})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(path.join(ROOT, 'POC', 'js', 'kg', 'ontology.js'), out);
console.log('wrote POC/js/kg/ontology.js (' + ttl.length + ' TTL bytes, ' + cqs.length + ' CQs)');
